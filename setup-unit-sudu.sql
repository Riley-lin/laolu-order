-- ============================================================
-- 🍢 素肚單位補標（2026-07-27 Riley 交辦，紙本菜單同步）
-- 用法：Supabase → SQL Editor → 貼整份 → Run（免通行碼）
--
-- 為什麼要改：素肚 21 元賣的是「半個」，紙本菜單已標「/半個」，
-- 但線上菜單 7/19 做過「單位大掃除」把單位全清空（只留年糕/鳥蛋），
-- 導致客人在網站上看不出來，容易誤會 21 元是一整個 → 現場糾紛。
-- 這份只動 menu_items 的 unit 欄，價格、優惠、排序、訂單資料都不碰。
-- 重跑安全（跑幾次結果都一樣）。
-- ============================================================

update public.menu_items
   set unit = '半個'
 where name = '素肚';

-- 自我體檢：應回 3 列（年糕 一份4條、鳥蛋 一份4顆、素肚 半個）
select name, unit from public.menu_items where unit <> '' order by name;
